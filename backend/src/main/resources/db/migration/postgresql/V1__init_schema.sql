-- FinPath Schema Migration V1
-- Creates all persistent entities for FinPath

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL DEFAULT 'ROLE_USER',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    display_name VARCHAR(255),
    age_range VARCHAR(50),
    country VARCHAR(100),
    state_region VARCHAR(100),
    education_employment_status VARCHAR(100),
    occupation VARCHAR(150),
    skills TEXT,
    experience_level VARCHAR(50),
    interests TEXT,
    available_hours_per_week INT DEFAULT 10,
    equipment_resources TEXT,
    willingness_to_learn BOOLEAN DEFAULT TRUE,
    preferred_income_model VARCHAR(100),
    onboarding_completed BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_profile_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS financial_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    monthly_take_home_income DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    monthly_essential_expenses DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    monthly_discretionary_expenses DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    monthly_debt_repayments DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    current_savings DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    other_recurring_income DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    available_startup_budget DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    debt_included_in_expenses BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_financial_profile_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS financial_goals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    goal_type VARCHAR(100) NOT NULL,
    title VARCHAR(255) NOT NULL,
    target_amount DECIMAL(14,2) NOT NULL,
    current_allocated DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    deadline DATE NOT NULL,
    priority VARCHAR(50) NOT NULL DEFAULT 'MEDIUM',
    currency VARCHAR(10) NOT NULL DEFAULT 'USD',
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_goals_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    type VARCHAR(50) NOT NULL,
    category VARCHAR(100) NOT NULL,
    amount DECIMAL(14,2) NOT NULL,
    description VARCHAR(500),
    transaction_date DATE NOT NULL,
    goal_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_transactions_goal FOREIGN KEY (goal_id) REFERENCES financial_goals(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS opportunity_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    slug VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    icon VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    target_customer VARCHAR(255) NOT NULL,
    potential_solution TEXT NOT NULL,
    required_skills TEXT NOT NULL,
    initial_cost_min DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    initial_cost_max DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    pricing_model VARCHAR(100),
    competition_notes TEXT,
    difficulty VARCHAR(50) NOT NULL DEFAULT 'MEDIUM',
    time_commitment VARCHAR(100),
    business_model VARCHAR(100),
    validation_status VARCHAR(50) NOT NULL DEFAULT 'NOT_STARTED',
    base_fit_score INT NOT NULL DEFAULT 75,
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    is_user_submitted BOOLEAN NOT NULL DEFAULT FALSE,
    created_by_user_id BIGINT,
    is_approved BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_opp_category FOREIGN KEY (category_id) REFERENCES opportunity_categories(id) ON DELETE SET NULL,
    CONSTRAINT fk_opp_creator FOREIGN KEY (created_by_user_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS saved_opportunities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    opportunity_id BIGINT NOT NULL,
    saved_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_saved_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_saved_opp FOREIGN KEY (opportunity_id) REFERENCES opportunities(id) ON DELETE CASCADE,
    CONSTRAINT uq_saved_user_opp UNIQUE (user_id, opportunity_id)
);

CREATE TABLE IF NOT EXISTS opportunity_validations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    opportunity_id BIGINT NOT NULL,
    stage VARCHAR(50) NOT NULL DEFAULT 'NOT_STARTED',
    problem_statement TEXT,
    target_customer_profile TEXT,
    hypotheses_to_test TEXT,
    interview_question_suggestions TEXT,
    people_interviewed_count INT NOT NULL DEFAULT 0,
    confirmed_problem_count INT NOT NULL DEFAULT 0,
    current_alternatives TEXT,
    willingness_to_pay_evidence TEXT,
    estimated_solution_cost DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    validation_notes TEXT,
    next_experiment TEXT,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_val_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_val_opp FOREIGN KEY (opportunity_id) REFERENCES opportunities(id) ON DELETE CASCADE,
    CONSTRAINT uq_val_user_opp UNIQUE (user_id, opportunity_id)
);

CREATE TABLE IF NOT EXISTS customer_interview_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    validation_id BIGINT NOT NULL,
    interviewee_name VARCHAR(150),
    customer_type VARCHAR(100),
    notes TEXT NOT NULL,
    confirmed_problem BOOLEAN NOT NULL DEFAULT FALSE,
    willingness_to_pay_amount DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    interview_date DATE NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_note_val FOREIGN KEY (validation_id) REFERENCES opportunity_validations(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS roadmaps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    goal_id BIGINT,
    opportunity_id BIGINT,
    title VARCHAR(255) NOT NULL,
    duration_months INT NOT NULL DEFAULT 6,
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_roadmap_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_roadmap_goal FOREIGN KEY (goal_id) REFERENCES financial_goals(id) ON DELETE SET NULL,
    CONSTRAINT fk_roadmap_opp FOREIGN KEY (opportunity_id) REFERENCES opportunities(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS roadmap_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roadmap_id BIGINT NOT NULL,
    stage VARCHAR(100) NOT NULL,
    stage_index INT NOT NULL DEFAULT 0,
    task_index INT NOT NULL DEFAULT 0,
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    due_date DATE,
    priority VARCHAR(50) NOT NULL DEFAULT 'MEDIUM',
    estimated_hours DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    estimated_cost DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    is_completed BOOLEAN NOT NULL DEFAULT FALSE,
    completed_at TIMESTAMP,
    success_criteria TEXT,
    dependencies VARCHAR(255),
    CONSTRAINT fk_task_roadmap FOREIGN KEY (roadmap_id) REFERENCES roadmaps(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS business_scenarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    opportunity_id BIGINT,
    name VARCHAR(150) NOT NULL,
    price_per_customer DECIMAL(14,2) NOT NULL,
    expected_customers INT NOT NULL,
    variable_cost_per_customer DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    monthly_fixed_expenses DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    initial_setup_costs DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    customer_acquisition_cost DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    qualified_leads INT NOT NULL DEFAULT 0,
    conversion_rate DECIMAL(6,4) NOT NULL DEFAULT 0.0500,
    gross_revenue DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    operating_profit DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    break_even_customers INT NOT NULL DEFAULT 0,
    required_leads INT NOT NULL DEFAULT 0,
    cost_recovery_months DECIMAL(8,2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_scenario_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_scenario_opp FOREIGN KEY (opportunity_id) REFERENCES opportunities(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS user_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    theme VARCHAR(50) NOT NULL DEFAULT 'terracotta-warm',
    email_notifications BOOLEAN NOT NULL DEFAULT TRUE,
    privacy_mode BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_settings_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

